using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text.RegularExpressions;
using DiskCardGame;
using HarmonyLib;

namespace SimplifiedChineseLanguagePack
{
    internal static class PackManagementLocalization
    {
        private const string DescriptionPattern = "Cards in this pack: {0} and {1} other{2}.";
        private static FieldInfo customDescription;
        private static FieldInfo generatedDescription;
        private static FieldInfo customTitle;
        private static FieldInfo generatedTitle;
        private static PropertyInfo cardsProperty;
        private static Type cardPackType;
        private static Type encounterPackType;
        private static readonly Regex EncounterDescription = new(@"^Contains (\d+) encounters(?: from (.*))?\.$", RegexOptions.Singleline);
        private static bool installed;

        internal static void Initialize()
        {
            if (installed)
            {
                return;
            }
            Type packInfo = FindOptionalType("Infiniscryption.PackManagement.PackInfo");
            if (packInfo == null)
            {
                return;
            }
            cardsProperty = packInfo.GetProperty("Cards", BindingFlags.Instance | BindingFlags.Public);
            MethodInfo descriptionGetter = packInfo.GetProperty("Description", BindingFlags.Instance | BindingFlags.Public)?.GetGetMethod();
            customDescription = descriptionGetter?.DeclaringType.GetField("_description", BindingFlags.Instance | BindingFlags.NonPublic);
            generatedDescription = descriptionGetter?.DeclaringType.GetField("AutoGeneratedDescription", BindingFlags.Instance | BindingFlags.NonPublic)
                ?? descriptionGetter?.DeclaringType.GetField("_autoGeneratedDescription", BindingFlags.Instance | BindingFlags.NonPublic);
            if (customDescription == null || generatedDescription == null || cardsProperty == null || descriptionGetter == null)
            {
                return;
            }
            cardPackType = packInfo;
            encounterPackType = packInfo.Assembly.GetType("Infiniscryption.PackManagement.EncounterPackInfo", false);
            var harmony = new Harmony(SimplifiedChineseLanguagePackPlugin.GUID + ".pack_descriptions");
            harmony.Patch(descriptionGetter, postfix: new HarmonyMethod(typeof(PackManagementLocalization), nameof(DescriptionPostfix)));
            MethodInfo titleGetter = packInfo.GetProperty("Title", BindingFlags.Instance | BindingFlags.Public)?.GetGetMethod();
            customTitle = titleGetter?.DeclaringType.GetField("_title", BindingFlags.Instance | BindingFlags.NonPublic);
            generatedTitle = titleGetter?.DeclaringType.GetField("AutoGeneratedTitle", BindingFlags.Instance | BindingFlags.NonPublic)
                ?? titleGetter?.DeclaringType.GetField("_autoGeneratedTitle", BindingFlags.Instance | BindingFlags.NonPublic);
            if (customTitle != null && generatedTitle != null)
            {
                harmony.Patch(titleGetter, postfix: new HarmonyMethod(typeof(PackManagementLocalization), nameof(TitlePostfix)));
            }
            installed = true;
        }

        private static Type FindOptionalType(string name)
        {
            foreach (Assembly assembly in AppDomain.CurrentDomain.GetAssemblies())
            {
                Type type = assembly.GetType(name, false);
                if (type != null) return type;
            }
            return null;
        }

        private static void TitlePostfix(object __instance, ref string __result)
        {
            bool encounter = encounterPackType?.IsInstanceOfType(__instance) == true;
            string prefix = encounter ? "Encounters Pack: " : "Card Pack: ";
            if ((!cardPackType.IsInstanceOfType(__instance) && !encounter) || !string.IsNullOrEmpty(customTitle.GetValue(__instance) as string)) return;
            string generated = generatedTitle.GetValue(__instance) as string;
            if (generated == null || !generated.StartsWith(prefix, StringComparison.Ordinal) || __result != generated) return;
            // The card pack fallback contains a raw ModPrefix. Encounter packs
            // instead use an already localized Title and keep their own path.
            string pattern = Localization.Translate(prefix + "{0}");
            if (pattern == prefix + "{0}") return;
            string title = generated.Substring(prefix.Length);
            __result = string.Format(pattern, encounter ? title : Localization.Translate(title));
        }

        private static void DescriptionPostfix(object __instance, ref string __result)
        {
            if (encounterPackType?.IsInstanceOfType(__instance) == true)
            {
                TranslateEncounterDescription(__instance, ref __result);
                return;
            }
            // Newer Pack Management versions share this getter with encounter
            // packs through PackInfoBase. Only card packs use this template.
            if (!cardPackType.IsInstanceOfType(__instance) || !string.IsNullOrEmpty(customDescription.GetValue(__instance) as string))
            {
                return;
            }
            string generated = generatedDescription.GetValue(__instance) as string;
            if (generated == null || !generated.StartsWith("Cards in this pack: ", StringComparison.Ordinal) ||
                __result != generated) return;
            Language language = Localization.CurrentLanguage;
            string pattern = Localization.Translate(DescriptionPattern);
            if (pattern == DescriptionPattern && language != Language.English)
            {
                return;
            }
            var cards = (cardsProperty.GetValue(__instance, null) as IEnumerable<CardInfo>)?.ToList();
            if (cards == null || cards.Count == 0)
            {
                return;
            }

            // PackInfo caches a fully interpolated English sentence containing
            // card names from the language active at its first initialization.
            // Rebuild this generated description from the translated template
            // and current names; explicit pack descriptions use their own path.
            string names = string.Join(", ", cards.Take(7).Select(card => card?.DisplayedNameLocalized ?? string.Empty));
            int remaining = Math.Max(0, cards.Count - 7);
            __result = string.Format(pattern, names, remaining, remaining > 1 ? "s" : string.Empty);
        }

        private static void TranslateEncounterDescription(object instance, ref string result)
        {
            if (!string.IsNullOrEmpty(customDescription.GetValue(instance) as string)) return;
            string generated = generatedDescription.GetValue(instance) as string;
            if (generated == null || result != generated) return;
            Match match = EncounterDescription.Match(generated);
            if (!match.Success || !int.TryParse(match.Groups[1].Value, out int count)) return;
            bool hasTitle = match.Groups[2].Success;
            string source = "Contains {0} " + (count == 1 ? "encounter" : "encounters") + (hasTitle ? " from {1}." : ".");
            string pattern = Localization.Translate(source);
            if (pattern == source) return;
            // The encounter caller already obtained a localized pack Title.
            // Keep that exact value, including markup and later mod changes.
            result = string.Format(pattern, count, match.Groups[2].Value);
        }
    }
}
